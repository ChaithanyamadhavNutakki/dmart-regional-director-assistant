def main():
    log_path = ROOT / "logs" / "runs.jsonl"
    transcript_path = ROOT / "outputs" / "acceptance_transcript.md"
    log_path.parent.mkdir(parents=True, exist_ok=True)
    transcript_path.parent.mkdir(parents=True, exist_ok=True)
    log_path.write_text("", encoding="utf-8")

    os.environ["AGENT_LOG_PATH"] = str(log_path)
    os.environ["WEATHER_MODE"] = "stub"
    os.environ.pop("SIMULATE_DB_FAILURES", None)
    clear_all_sessions()

    transcript = [
        "# Part C — Acceptance transcript",
        "",
        "Generated by scripts/run_acceptance.py from the fixed twenty-case acceptance set.",
        "",
    ]
    failures = []

    for case_id, session_id, question, simulated_failures in CASES:
        if simulated_failures:
            os.environ["SIMULATE_DB_FAILURES"] = str(simulated_failures)
        else:
            os.environ.pop("SIMULATE_DB_FAILURES", None)

        result = handle(question, session_id)
        expected_status, expected_intent, required_content = EXPECTED[case_id]
        answer = str(result.get("answer_text", ""))
        checks = {
            "status": result.get("status") == expected_status,
            "intent": result.get("intent") == expected_intent,
            "content": all(part.casefold() in answer.casefold() for part in required_content),
            "grounding": result.get("ungrounded_numbers") == 0,
        }

        if case_id == "A04":
            checks["confidence"] = result.get("confidence", 1) < 0.7
        if case_id == "A06":
            checks["confidence"] = 0.7 <= result.get("confidence", 0) < 1.0
        if case_id in {"A19", "A20"}:
            checks["attempts"] = result.get("attempts") == 3
        if case_id == "A20":
            checks["no_figure"] = "INR" not in answer

        passed = all(checks.values())
        if not passed:
            failures.append((case_id, checks, result))

        transcript.extend(
            [
                f"## {case_id} — {'PASS' if passed else 'FAIL'}",
                f"- Session: {session_id}",
                f"- Question: {question}",
                f"- Expected status / intent: {expected_status} / {expected_intent}",
                f"- Actual status / intent: {result.get('status')} / {result.get('intent')}",
                f"- Confidence: {result.get('confidence')}",
                f"- Route: {result.get('route')}",
                f"- Attempts: {result.get('attempts')}",
                f"- Checks: {checks}",
                "- Answer:",
                "",
                "  " + answer.replace("\n", "\n  "),
                "",
            ]
        )

    os.environ.pop("SIMULATE_DB_FAILURES", None)
    transcript_path.write_text("\n".join(transcript), encoding="utf-8")

    with log_path.open("r", encoding="utf-8") as log_file:
        log_records = [json.loads(line) for line in log_file if line.strip()]

    log_checks = (
        len(log_records) == len(CASES)
        and all(item.get("ungrounded_numbers") == 0 for item in log_records)
    )

    print(f"Acceptance cases passed: {len(CASES) - len(failures)} / {len(CASES)}")
    print(f"Audit records: {len(log_records)}")
    print(f"Audit integrity: {'PASS' if log_checks else 'FAIL'}")
    print(f"Transcript: {transcript_path.relative_to(ROOT)}")

    if failures or not log_checks:
        for case_id, checks, result in failures:
            print(f"FAILED {case_id}: {checks}; answer={result.get('answer_text')}")
        raise SystemExit(1)


if __name__ == "__main__":
    main()
