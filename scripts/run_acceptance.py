"""Run the twenty fixed Part C acceptance cases and save transcript/logs."""

from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
os.chdir(ROOT)
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from agent.run_agent import clear_all_sessions, handle


CASES = [
    ("A01", "s1", "What was Pune's revenue on 15 May 2026?", 0),
    ("A02", "s1", "And the target?", 0),
    ("A03", "s1", "How about Mumbai?", 0),
    ("A04", "s2", "How is Hyderabad doing?", 0),
    ("A05", "s2", "revenue on 2026-05-15", 0),
    ("A06", "s3", "What was Hydrabad's turnover yesterday?", 0),
    ("A07", "s4", "Did Pune hit its target on 2026-05-16?", 0),
    ("A08", "s4", "Did Pune hit its target on 2026-05-20?", 0),
    ("A09", "s4", "Did Mumbai hit its target on 2026-05-21?", 0),
    ("A10", "s5", "Which store had the highest average revenue between 2026-05-01 and 2026-05-31?", 0),
    ("A11", "s5", "Which store had the lowest revenue on 2026-06-10?", 0),
    ("A12", "s6", "Which stores are below the reorder threshold for Amul Milk?", 0),
    ("A13", "s6", "What are customers saying about Hyderabad?", 0),
    ("A14", "s7", "What was Pune's profit margin on 2026-05-15?", 0),
    ("A15", "s8", "What is the capital of India?", 0),
    ("A16", "s9", "What was Mumbai's revenue on 2026-07-15?", 0),
    ("A17", "s10", "Why is Pune's revenue so low?", 0),
    ("A18", "s11", "What was Kolkata's revenue on 2026-05-15?", 0),
    ("A19", "s12", "What was Pune's revenue on 15 May 2026?", 2),
    ("A20", "s13", "What was Pune's revenue on 15 May 2026?", 3),
]


def main():
    log_path = ROOT / "logs" / "runs.jsonl"
    transcript_path = ROOT / "outputs" / "acceptance_transcript.md"
    log_path.parent.mkdir(parents=True, exist_ok=True)
    transcript_path.parent.mkdir(parents=True, exist_ok=True)
    log_path.write_text("", encoding="utf-8")

    os.environ["AGENT_LOG_PATH"] = str(log_path)
    os.environ.pop("SIMULATE_DB_FAILURES", None)
    clear_all_sessions()

    transcript = [
        "# Part C — Acceptance transcript",
        "",
        "This transcript is generated by scripts/run_acceptance.py from the fixed twenty-case acceptance set.",
        "",
    ]

    for case_id, session_id, question, simulated_failures in CASES:
        if simulated_failures:
            os.environ["SIMULATE_DB_FAILURES"] = str(simulated_failures)
        else:
            os.environ.pop("SIMULATE_DB_FAILURES", None)

        result = handle(question, session_id)
        transcript.extend(
            [
                f"## {case_id}",
                f"- Session: {session_id}",
                f"- Question: {question}",
                f"- Status: {result.get('status')}",
                f"- Intent: {result.get('intent')}",
                f"- Confidence: {result.get('confidence')}",
                f"- Route: {result.get('route')}",
                f"- Attempts: {result.get('attempts')}",
                "- Answer:",
                "",
                "  " + str(result.get("answer_text", "")).replace("\n", "\n  "),
                "",
            ]
        )

    os.environ.pop("SIMULATE_DB_FAILURES", None)
    transcript_path.write_text("\n".join(transcript), encoding="utf-8")
    print(f"Acceptance cases written: {len(CASES)}")
    print(f"Audit log: {log_path.relative_to(ROOT)}")
    print(f"Transcript: {transcript_path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
